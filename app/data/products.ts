import type { Product, ProductStatus } from '~/types'
import { seeded } from '~/data/random'

// Демо-каталог. Генерируется детерминированно (без Math.random), чтобы данные
// были одинаковыми при каждой загрузке и в тестах.

const CATALOG: Record<string, string[]> = {
  Электроника: ['Беспроводные наушники', 'Умные часы', 'Портативная колонка', 'Powerbank 20000 мАч', 'Веб-камера Full HD', 'Механическая клавиатура', 'Игровая мышь', 'USB-C хаб', 'Монитор 27"', 'Электронная книга'],
  Одежда: ['Худи оверсайз', 'Джинсы прямые', 'Футболка базовая', 'Куртка ветровка', 'Свитер шерстяной', 'Кроссовки беговые', 'Кепка', 'Шарф кашемировый', 'Платье миди', 'Рубашка льняная'],
  Дом: ['Кофемашина капсульная', 'Чайник стеклянный', 'Набор кастрюль', 'Плед флисовый', 'Настольная лампа', 'Увлажнитель воздуха', 'Робот-пылесос', 'Комплект постельного белья', 'Набор ножей', 'Термокружка'],
  Красота: ['Крем для лица', 'Сыворотка с витамином C', 'Шампунь безсульфатный', 'Фен-щётка', 'Парфюм 50 мл', 'Набор кистей', 'Маска для волос', 'Солнцезащитный крем SPF 50'],
  Спорт: ['Коврик для йоги', 'Гантели 2×5 кг', 'Велосипедный шлем', 'Бутылка для воды', 'Скакалка скоростная', 'Фитнес-резинки', 'Рюкзак туристический', 'Палатка двухместная'],
}

const PREFIX: Record<string, string> = { Электроника: 'EL', Одежда: 'CL', Дом: 'HM', Красота: 'BT', Спорт: 'SP' }

// Около 10% товаров закончились, ещё ~15% на исходе — чтобы было что подсвечивать
function stockFor(r: number): number {
  if (r < 0.1) return 0
  if (r < 0.25) return 1 + Math.floor(r * 12) % 4
  return 5 + Math.floor(r * 1000) % 76
}

export function createDemoProducts(): Product[] {
  const random = seeded(42)
  const products: Product[] = []
  let id = 1
  for (const [category, names] of Object.entries(CATALOG)) {
    names.forEach((name, i) => {
      const r = random()
      const status: ProductStatus = r < 0.12 ? 'archived' : r < 0.25 ? 'draft' : 'active'
      products.push({
        id,
        name,
        sku: `${PREFIX[category]}-${String(1000 + i * 37 + id).padStart(4, '0')}`,
        // цена кратна 500 драмам — так выглядит правдоподобно
        price: Math.round((3000 + random() * 147000) / 500) * 500,
        stock: stockFor(random()),
        category,
        status,
      })
      id += 1
    })
  }
  return products
}
